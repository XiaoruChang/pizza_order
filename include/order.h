#ifndef PIZZA_ORDER_H
#define PIZZA_ORDER_H

#include "models.h"
#include "result.h"
#include "sales.h"

_Static_assert(PIZZA_NAME_CAPACITY == SALES_NAME_CAPACITY,
               "Sales snapshots must preserve historical names");

/* Read-only pricing of 1..MAX_ORDER_LINES entries in one menu revision.
 * Fill historical names/prices and the total; no order ID is allocated yet. */
Result order_quote(const AppState *state, const OrderDraft *draft,
                    OrderQuote *out_quote);

/* Active customer only. Recompute the entire draft; verify the confirmed
 * revision, configurations, historical names, quantities and prices. A mismatched quote
 * returns QUOTE_CHANGED, never silently charges a different total.
 * Commit the PAID order, debit and next ID in ONE durable state replacement.
 * Any failure leaves both memory and disk unchanged and out_order_id untouched.
 * A returned order ID is generated by this call; confirmed_quote is not trusted.
 * Repeating a successful call is a NEW purchase, not an idempotent retry. */
Result order_submit(AppState *state, const Session *customer,
                     const OrderDraft *draft,
                     const OrderQuote *confirmed_quote, OrderId *out_order_id);

/* Customer: own orders only. Manager: any order. Returns an independent copy. */
Result order_get(const AppState *state, const Session *session,
                  OrderId order_id, Order *out_order);

/* An owned, complete read-only projection for the existing sales module.
 * Initialize to {0}; free before reuse. Inner lines are owned by this snapshot.
 * Do not modify pointers/counts or free individual allocations yourself. */
typedef struct {
    const SalesOrder *orders;
    size_t count;
} SalesSnapshot;

/* Manager only. All saved orders, explicit status mapping. Group pizzas by
 * stable topping/flavour ID; use the saved topping name. revenue_cents is the
 * saved line subtotal, already multiplied by quantity. */
Result order_export_sales(const AppState *state, const Session *manager,
                           SalesSnapshot *out_snapshot);
void order_sales_snapshot_free(SalesSnapshot *snapshot); /* NULL/empty OK. */

#endif
